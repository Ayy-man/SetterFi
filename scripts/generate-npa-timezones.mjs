/**
 * Projects the pinned libphonenumber US prefix slice into a deterministic NPA map.
 *
 * The source is deliberately vendored: quiet-hours decisions must not depend on a
 * network response or on timezone metadata changing between scheduling and send.
 */

import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const REPOSITORY_ROOT = fileURLToPath(new URL("../", import.meta.url));
const SOURCE_RELATIVE_PATH = "src/lib/quiet-hours/libphonenumber-map-data-us.txt";
const OUTPUT_RELATIVE_PATH = "src/lib/quiet-hours/npa-timezones.generated.ts";
const SOURCE_PATH = fileURLToPath(new URL(`../${SOURCE_RELATIVE_PATH}`, import.meta.url));
const OUTPUT_PATH = fileURLToPath(new URL(`../${OUTPUT_RELATIVE_PATH}`, import.meta.url));
const UPSTREAM_TAG = "v9.0.14";
const UPSTREAM_PATH = "resources/timezones/map_data.txt";
const UPSTREAM_URL =
  `https://github.com/google/libphonenumber/blob/${UPSTREAM_TAG}/${UPSTREAM_PATH}`;

function fail(message) {
  throw new Error(`${message}: ${SOURCE_RELATIVE_PATH}`);
}

async function readPinnedSource() {
  try {
    return await readFile(SOURCE_PATH, "utf8");
  } catch (cause) {
    if (cause && typeof cause === "object" && "code" in cause && cause.code === "ENOENT") {
      fail("Missing pinned libphonenumber source slice");
    }
    throw cause;
  }
}

function projectNpaTimezones(source) {
  const byNpa = new Map();

  for (const [index, rawLine] of source.split(/\r?\n/u).entries()) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;

    const separator = line.indexOf("|");
    if (separator < 0) fail(`Malformed source line ${index + 1}`);
    const prefix = line.slice(0, separator);
    if (!/^1[2-9][0-9]{2,}$/u.test(prefix)) {
      fail(`Non-US NANP prefix on source line ${index + 1}`);
    }

    const timezones = line.slice(separator + 1).split("&").filter(Boolean);
    if (timezones.length === 0) fail(`Missing timezone on source line ${index + 1}`);

    const npa = prefix.slice(1, 4);
    const candidates = byNpa.get(npa) ?? new Set();
    for (const timezone of timezones) candidates.add(timezone);
    byNpa.set(npa, candidates);
  }

  if (byNpa.size === 0) fail("Pinned source slice produced no US NPA rows");
  return [...byNpa.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([npa, candidates]) => [npa, [...candidates].sort()]);
}

function render(entries, checksum) {
  const rows = entries.map(([npa, timezones]) =>
    `  "${npa}": ${JSON.stringify(timezones)},`
  );
  return [
    "/**",
    " * Generated by scripts/generate-npa-timezones.mjs. Do not edit by hand.",
    ` * Source: google/libphonenumber ${UPSTREAM_TAG} ${UPSTREAM_PATH}`,
    ` * Upstream: ${UPSTREAM_URL}`,
    ` * Committed source-slice SHA-256: ${checksum}`,
    " * License: Apache-2.0; see libphonenumber-NOTICE.txt beside the source slice.",
    " */",
    "",
    "export const NPA_TIMEZONES = {",
    ...rows,
    "} as const satisfies Readonly<Record<string, readonly string[]>>;",
    "",
  ].join("\n");
}

const source = await readPinnedSource();
const checksum = createHash("sha256").update(source).digest("hex");
const output = render(projectNpaTimezones(source), checksum);

await writeFile(OUTPUT_PATH, output, "utf8");
process.stdout.write(
  `Generated ${OUTPUT_RELATIVE_PATH} from ${SOURCE_RELATIVE_PATH} ` +
    `(${checksum}) under ${REPOSITORY_ROOT}\n`,
);
